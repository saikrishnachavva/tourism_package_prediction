# =============================================
# Streamlit App - Tourism Package Purchase Prediction
# Tourism Package Prediction - MLOps Pipeline
# =============================================
# This app loads the trained model committed to the
# GitHub repository and provides a user interface
# for predicting tourism package purchases.
# Deployed on Streamlit Community Cloud.

import streamlit as st
import pandas as pd
import joblib
import os

# ----- Load the Trained Model from the Repository -----
# On Streamlit Community Cloud, the app runs from the repo root.
# The model file is committed to the repository by the CI/CD pipeline.
model_path = os.path.join("tourism_package_prediction", "model", "best_tourism_model.joblib")
model = joblib.load(model_path)

# ----- Label Encoding Mappings (must match prep.py) -----
# These mappings are generated by LabelEncoder (alphabetical order)
contact_map = {"Company Invited": 0, "Self Enquiry": 1}
occupation_map = {"Free Lancer": 0, "Large Business": 1, "Salaried": 2, "Small Business": 3}
gender_map = {"Female": 0, "Male": 1}
product_map = {"Basic": 0, "Deluxe": 1, "King": 2, "Standard": 3, "Super Deluxe": 4}
marital_map = {"Divorced": 0, "Married": 1, "Single": 2}
designation_map = {"AVP": 0, "Executive": 1, "Manager": 2, "Senior Manager": 3, "VP": 4}

# ----- Streamlit UI -----
st.set_page_config(
    page_title="Wellness Tourism Package Prediction",
    page_icon="✈️",
    layout="wide"
)

st.title("✈️ Wellness Tourism Package - Purchase Prediction")
st.write("""
This application predicts whether a customer will purchase the **Wellness Tourism Package**
offered by **Visit with Us** travel company. Enter the customer details below to get a prediction.
""")

st.markdown("---")

# ----- Input Fields (organized in 3 columns) -----
col1, col2, col3 = st.columns(3)

with col1:
    st.subheader("👤 Customer Details")
    age = st.number_input("Age", min_value=18, max_value=100, value=30, step=1)
    gender = st.selectbox("Gender", list(gender_map.keys()))
    occupation = st.selectbox("Occupation", list(occupation_map.keys()))
    marital_status = st.selectbox("Marital Status", list(marital_map.keys()))
    designation = st.selectbox("Designation", list(designation_map.keys()))
    monthly_income = st.number_input("Monthly Income (₹)", min_value=1000, max_value=100000, value=20000, step=500)

with col2:
    st.subheader("🌍 Travel Details")
    type_of_contact = st.selectbox("Type of Contact", list(contact_map.keys()))
    city_tier = st.selectbox("City Tier", [1, 2, 3])
    num_persons = st.number_input("Number of Persons Visiting", min_value=1, max_value=10, value=2, step=1)
    num_children = st.number_input("Number of Children Visiting (below age 5)", min_value=0, max_value=10, value=0, step=1)
    num_trips = st.number_input("Average Number of Trips per Year", min_value=1, max_value=20, value=2, step=1)
    passport = st.selectbox("Has Passport?", ["No", "Yes"])
    own_car = st.selectbox("Owns a Car?", ["No", "Yes"])

with col3:
    st.subheader("📞 Interaction Data")
    product_pitched = st.selectbox("Product Pitched", list(product_map.keys()))
    preferred_property_star = st.selectbox("Preferred Property Star Rating", [3, 4, 5])
    duration_of_pitch = st.number_input("Duration of Pitch (minutes)", min_value=1, max_value=60, value=15, step=1)
    num_followups = st.number_input("Number of Follow-ups", min_value=1, max_value=10, value=3, step=1)
    pitch_satisfaction = st.slider("Pitch Satisfaction Score", min_value=1, max_value=5, value=3)

st.markdown("---")

# ----- Assemble Input into DataFrame -----
# Column order must match the training data exactly
input_data = pd.DataFrame([{
    'Age': age,
    'TypeofContact': contact_map[type_of_contact],
    'CityTier': city_tier,
    'DurationOfPitch': float(duration_of_pitch),
    'Occupation': occupation_map[occupation],
    'Gender': gender_map[gender],
    'NumberOfPersonVisiting': num_persons,
    'NumberOfFollowups': float(num_followups),
    'ProductPitched': product_map[product_pitched],
    'PreferredPropertyStar': float(preferred_property_star),
    'MaritalStatus': marital_map[marital_status],
    'NumberOfTrips': float(num_trips),
    'Passport': 1 if passport == "Yes" else 0,
    'PitchSatisfactionScore': pitch_satisfaction,
    'OwnCar': 1 if own_car == "Yes" else 0,
    'NumberOfChildrenVisiting': float(num_children),
    'Designation': designation_map[designation],
    'MonthlyIncome': float(monthly_income),
}])

# ----- Prediction -----
if st.button("🔮 Predict Purchase Likelihood"):
    prediction = model.predict(input_data)[0]
    probability = model.predict_proba(input_data)[0]

    st.subheader("📊 Prediction Result")

    if prediction == 1:
        st.success(f"✅ **The customer is LIKELY to purchase the Wellness Tourism Package!**")
        st.metric(label="Purchase Probability", value=f"{probability[1]*100:.1f}%")
    else:
        st.warning(f"❌ **The customer is UNLIKELY to purchase the Wellness Tourism Package.**")
        st.metric(label="Non-Purchase Probability", value=f"{probability[0]*100:.1f}%")

    # Display the input summary
    st.subheader("📋 Input Summary")
    st.dataframe(input_data.T.rename(columns={0: "Value"}))
